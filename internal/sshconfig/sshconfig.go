// Package sshconfig generates the OpenSSH client configuration and the
// known_hosts file that make plain `ssh` use tvbeat-auth.
package sshconfig

import (
	"bufio"
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"runtime"
	"strings"
	"text/template"

	"golang.org/x/crypto/ssh"

	"github.com/tvbeat/tvbeat-auth/internal/creds"
	"github.com/tvbeat/tvbeat-auth/internal/fsutil"
	"github.com/tvbeat/tvbeat-auth/internal/hosts"
	"github.com/tvbeat/tvbeat-auth/internal/site"
)

var lookPath = exec.LookPath

// IncludeLine is what we add to ~/.ssh/config.
const IncludeLine = "Include ~/.ssh/tvbeat/config"

const header = "# generated by `tvbeat-auth setup` - do not edit, re-run that command instead"

var configTmpl = template.Must(template.New("config").Parse(header + `
#
# Only the host names below involve tvbeat-auth at all; ssh matches them itself.
# ` + "`tvbeat-auth check-host <name>`" + ` gives the same answer from the command line.
Host {{.Patterns}}
  ProxyCommand {{.ProxyExe}} ssh-proxy %r %h %p
  User {{.Username}}
  IdentityFile {{.AgentCert}}
  IdentityFile {{.Key}}
  CertificateFile {{.Cert}}
  IdentitiesOnly yes
  CheckHostIP no
{{- if .HostCA}}
  UserKnownHostsFile {{.KnownHosts}}
  StrictHostKeyChecking yes
  UpdateHostKeys no
{{- end}}

# ssh reads key files before it runs the ProxyCommand, so a fresh certificate
# has to be in place by then: this makes sure of it (signing in if needed).
# It costs one quick local check when you already have a valid certificate.
Match host {{.MatchPatterns}} exec "{{.ExecExe}} prepare %h"
`))

// Data feeds the template.
type Data struct {
	Patterns      string
	MatchPatterns string
	ProxyExe      string
	ExecExe       string
	Username      string
	HostCA        bool
	// absolute paths: ssh expands ~ from the passwd database, which is not
	// always where os.UserHomeDir points (and Windows has no ~ at all)
	AgentCert, Key, Cert, KnownHosts string
}

// Patterns returns every ssh Host pattern for the site.
func Patterns(s *site.Site) []string {
	var p []string
	for i := range s.Clusters {
		c := &s.Clusters[i]
		p = append(p, "*."+c.Name, c.Name+"+*", c.Name, c.JumpHost())
	}
	return p
}

func quotePath(p string) string {
	p = filepath.ToSlash(p)
	if strings.ContainsAny(p, " \t") {
		return `"` + p + `"`
	}
	return p
}

// Render returns the generated ssh config.
func Render(s *site.Site, username, exe string, hostCA bool, paths creds.Paths) ([]byte, error) {
	exe = filepath.ToSlash(exe)
	proxyExe, execExe := exe, exe
	if strings.ContainsAny(exe, " \t") {
		proxyExe = `"` + exe + `"`
		// already inside double quotes; sh understands single quotes
		execExe = `'` + exe + `'`
	}
	var b bytes.Buffer
	err := configTmpl.Execute(&b, Data{
		Patterns:      strings.Join(Patterns(s), " "),
		MatchPatterns: strings.Join(Patterns(s), ","),
		ProxyExe:      proxyExe,
		ExecExe:       execExe,
		Username:      username,
		HostCA:        hostCA,
		AgentCert:     quotePath(paths.AgentCert),
		Key:           quotePath(paths.Key),
		Cert:          quotePath(paths.Cert),
		KnownHosts:    quotePath(paths.KnownHosts),
	})
	return b.Bytes(), err
}

// KnownHosts renders a known_hosts file trusting caKey for every host name
// spelling of every cluster, on any port.
func KnownHosts(s *site.Site, caKey string) []byte {
	var b bytes.Buffer
	b.WriteString(header + "\n")
	for i := range s.Clusters {
		c := &s.Clusters[i]
		var pats []string
		for _, p := range hosts.KnownHostsPatterns(c) {
			pats = append(pats, p, "["+p+"]:*")
		}
		fmt.Fprintf(&b, "@cert-authority %s %s\n", strings.Join(pats, ","), strings.TrimSpace(caKey))
	}
	return b.Bytes()
}

// HostCAKeys reads the CA keys back out of our known_hosts file.
func HostCAKeys(path string) ([]ssh.PublicKey, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var keys []ssh.PublicKey
	for len(b) > 0 {
		marker, _, key, _, rest, err := ssh.ParseKnownHosts(b)
		if err != nil {
			break
		}
		if marker == "cert-authority" {
			dup := false
			for _, k := range keys {
				if bytes.Equal(k.Marshal(), key.Marshal()) {
					dup = true
				}
			}
			if !dup {
				keys = append(keys, key)
			}
		}
		b = rest
	}
	return keys, nil
}

// Executable returns how the ssh config should invoke tvbeat-auth: a stable
// path, never a /nix/store path that a garbage collection may delete.
func Executable() string {
	self, err := os.Executable()
	if err != nil {
		return "tvbeat-auth"
	}
	selfReal, _ := filepath.EvalSymlinks(self)
	name := "tvbeat-auth"
	if runtime.GOOS == "windows" {
		name += ".exe"
	}
	exe := self
	if p, err := lookPath(name); err == nil {
		if pr, _ := filepath.EvalSymlinks(p); pr != "" && pr == selfReal {
			exe = p
		}
	}
	if strings.HasPrefix(exe, "/nix/store/") {
		// on PATH under some profile; let the shell find it
		exe = name
	}
	if strings.HasPrefix(exe, "/nix/store/") || runtime.GOOS == "windows" {
		// nix: on PATH via some profile, and store paths get garbage
		// collected. windows: the install puts it on PATH, and a path under
		// "C:\Users\John Smith" cannot be quoted for both ssh and cmd.exe
		exe = name
	}
	return exe
}

// IncludeResult says what happened to ~/.ssh/config.
type IncludeResult int

const (
	IncludeAlreadyPresent IncludeResult = iota
	IncludeAdded
	// IncludeManual means the file is managed by something else (e.g. a
	// read-only home-manager symlink) and the user has to add the line.
	IncludeManual
)

var includeRe = regexp.MustCompile(`(?im)^[ \t]*include[ \t]+("?)(~/\.ssh/)?tvbeat/config("?)[ \t]*$`)

// legacy lines written by tvbeat-ssh 1.x
var legacyRe = regexp.MustCompile("(?m)^# tvbeat configuration added by `tvbeat-ssh config` command\n|^Include tvbeat\\.conf\n\n?")

// EnsureInclude makes ~/.ssh/config include our file, at the very top so it
// takes precedence, without replacing a symlink with a regular file.
func EnsureInclude(sshDir string) (IncludeResult, string, error) {
	path := filepath.Join(sshDir, "config")

	target := path
	fi, err := os.Lstat(path)
	switch {
	case errors.Is(err, fs.ErrNotExist):
		if err := os.MkdirAll(sshDir, 0o700); err != nil {
			return 0, path, err
		}
		return IncludeAdded, path, fsutil.WriteFileAtomic(path, []byte(IncludeLine+"\n"), 0o600)
	case err != nil:
		return 0, path, err
	case fi.Mode()&os.ModeSymlink != 0:
		target, err = filepath.EvalSymlinks(path)
		if err != nil {
			return IncludeManual, path, nil
		}
	}

	content, err := os.ReadFile(target)
	if err != nil {
		return 0, target, err
	}
	if includeRe.Match(content) {
		return IncludeAlreadyPresent, target, nil
	}
	if strings.HasPrefix(target, "/nix/store/") || !writable(target) {
		return IncludeManual, target, nil
	}

	content = legacyRe.ReplaceAll(content, nil)
	var b bytes.Buffer
	b.WriteString("# added by `tvbeat-auth setup` - keep this first so it takes precedence\n")
	b.WriteString(IncludeLine + "\n\n")
	b.Write(content)

	st, err := os.Stat(target)
	if err != nil {
		return 0, target, err
	}
	// rename within the directory of the real file, keeping its mode, so a
	// symlinked ~/.ssh/config stays a symlink
	if err := fsutil.WriteFileAtomic(target, b.Bytes(), st.Mode().Perm()); err != nil {
		return 0, target, err
	}
	return IncludeAdded, target, nil
}

func writable(path string) bool {
	st, err := os.Stat(path)
	if err != nil {
		return false
	}
	if st.Mode().Perm()&0o200 == 0 {
		return false
	}
	f, err := os.CreateTemp(filepath.Dir(path), ".tvbeat-auth-probe*")
	if err != nil {
		return false
	}
	f.Close()
	os.Remove(f.Name())
	return true
}

// RetireLegacy neutralises the 1.x ~/.ssh/tvbeat.conf, keeping a backup.
func RetireLegacy(sshDir string) (string, error) {
	p := filepath.Join(sshDir, "tvbeat.conf")
	b, err := os.ReadFile(p)
	if err != nil {
		return "", nil
	}
	if !bytes.Contains(b, []byte("tvbeat-ssh")) {
		return "", nil
	}
	backup := p + ".old"
	if err := os.Rename(p, backup); err != nil {
		return "", err
	}
	return backup, nil
}

// Write generates ~/.ssh/tvbeat/config and known_hosts.
func Write(s *site.Site, username, caKey string) (creds.Paths, error) {
	paths, err := creds.SSHPaths()
	if err != nil {
		return paths, err
	}
	if err := os.MkdirAll(paths.Dir, 0o700); err != nil {
		return paths, err
	}
	cfg, err := Render(s, username, Executable(), caKey != "", paths)
	if err != nil {
		return paths, err
	}
	if err := fsutil.WriteFileAtomic(paths.Config, cfg, 0o644); err != nil {
		return paths, err
	}
	if caKey != "" {
		if err := fsutil.WriteFileAtomic(paths.KnownHosts, KnownHosts(s, caKey), 0o644); err != nil {
			return paths, err
		}
	} else {
		os.Remove(paths.KnownHosts)
	}
	return paths, nil
}

// HasInclude reports whether ~/.ssh/config includes our file.
func HasInclude(sshDir string) bool {
	f, err := os.Open(filepath.Join(sshDir, "config"))
	if err != nil {
		return false
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		if includeRe.MatchString(sc.Text()) {
			return true
		}
	}
	return false
}
